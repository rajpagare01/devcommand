CREATE TABLE external_identity_verification_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_identity_id BIGINT NOT NULL,
    challenge_hash VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    attempt_count INT DEFAULT 0 NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_external_identity_challenge FOREIGN KEY (external_identity_id) REFERENCES external_identities (id) ON DELETE CASCADE
);

CREATE INDEX idx_challenge_external_identity_id ON external_identity_verification_challenges(external_identity_id);
